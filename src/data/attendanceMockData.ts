// Helper to compute summary counts
export function calculateAttendanceMetrics(records: Record<string, StudentAttendanceRecord>) {
  const values = Object.values(records);
  const totalEnrolled = values.length;
  const presentCount = values.filter((r) => r.status === 'PRESENT').length;
  const lateCount = values.filter((r) => r.status === 'LATE').length;
  const absentCount = values.filter((r) => r.status === 'ABSENT').length;

  // Present and Late are considered attended
  const attendedCount = presentCount + lateCount;
  const attendanceRate = totalEnrolled > 0 ? Math.round((attendedCount / totalEnrolled) * 100) : 0;

  return {
    totalEnrolled,
    presentCount,
    absentCount,
    lateCount,
    attendanceRate,
  };
}

